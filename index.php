<script>
let players = [];

function onYouTubeIframeAPIReady() {

    document.querySelectorAll('.yt-video').forEach((iframe, index) => {

        players[index] = new YT.Player(iframe, {

            playerVars: {
                autoplay: 1,
                mute: 1,
                controls: 0,
                rel: 0,
                playsinline: 1,
                loop: 1,
                playlist: iframe.src.match(/embed\/([^?]+)/)[1]
            },

            events: {

                onReady: function(event) {

                    event.target.mute();
                    event.target.playVideo();

                    const card = iframe.closest('.video-slide-item');

                    card.addEventListener('mouseenter', () => {

                        // sab videos mute karo
                        players.forEach(player => {
                            if (player && player.mute) {
                                player.mute();
                            }
                        });

                        // sirf hovered video unmute karo
                        event.target.unMute();

                    });

                    card.addEventListener('mouseleave', () => {
                        event.target.mute();
                    });

                },

                onStateChange: function(event) {

                    // video end hone par fir se start
                    if (event.data === YT.PlayerState.ENDED) {
                        event.target.seekTo(0);
                        event.target.playVideo();
                    }

                }

            }

        });

    });
}
</script>


